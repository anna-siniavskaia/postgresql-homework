DROP SCHEMA IF EXISTS hw5 CASCADE;
CREATE SCHEMA hw5;

-- LIKE: surnames of exactly five characters after the final space.
CREATE VIEW hw5.five_letter_surnames AS
SELECT passenger_name
FROM hw4.tickets
WHERE passenger_name LIKE '% _____';

-- Treat reverse flights as one undirected city pair.
CREATE VIEW hw5.canonical_routes AS
SELECT DISTINCT
       least(dep.city, arr.city) AS city_1,
       greatest(dep.city, arr.city) AS city_2
FROM hw4.flights f
JOIN hw4.airports dep ON dep.airport_code = f.departure_airport
JOIN hw4.airports arr ON arr.airport_code = f.arrival_airport
WHERE f.aircraft_code = '773';

-- LEFT JOIN retains routes without ticket sales; their prices remain NULL.
CREATE VIEW hw5.route_price_summary AS
SELECT dep.city AS departure_city, arr.city AS arrival_city,
       max(tf.amount) AS max_price, min(tf.amount) AS min_price
FROM hw4.flights f
JOIN hw4.airports dep ON dep.airport_code = f.departure_airport
JOIN hw4.airports arr ON arr.airport_code = f.arrival_airport
LEFT JOIN hw4.ticket_flights tf ON tf.flight_id = f.flight_id
GROUP BY dep.city, arr.city;

-- UNION removes overlapping ranges generated by multiple seed rows.
CREATE VIEW hw5.booking_ranges AS
WITH RECURSIVE ranges(min_sum, max_sum) AS (
    VALUES (0::numeric, 100000::numeric),
           (100000::numeric, 200000::numeric),
           (200000::numeric, 300000::numeric)
    UNION
    SELECT min_sum + 100000, max_sum + 100000
    FROM ranges
    WHERE max_sum < (SELECT max(total_amount) FROM hw4.bookings)
)
SELECT min_sum, max_sum FROM ranges;

-- EXCEPT subtracts destinations reachable directly from Moscow.
CREATE VIEW hw5.cities_without_moscow_flights AS
SELECT city
FROM hw4.airports
WHERE city <> 'Москва'
EXCEPT
SELECT arr.city
FROM hw4.flights f
JOIN hw4.airports dep ON dep.airport_code = f.departure_airport
JOIN hw4.airports arr ON arr.airport_code = f.arrival_airport
WHERE dep.city = 'Москва';

CREATE VIEW hw5.possible_city_routes AS
WITH cities AS (SELECT DISTINCT city FROM hw4.airports)
SELECT count(*) AS routes_possible
FROM cities a
JOIN cities b ON a.city <> b.city;
